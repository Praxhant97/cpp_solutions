void solve() {
    ll n;
    cin>>n;
    vector<ll>arr(n);
    for(int i=0;i<n;i++){
        cin>>arr[i];
    }
    ll sum=0;
    ll count=0;
    for(int i=0;i<n;i++){
        if(arr[i]>0){
            count++;
        }
        sum+=arr[i];
    }
    ll NewSum=sum-count;
    ll sub=n-1-NewSum;
    ll x=0;
    cout<<count-max(x,sub)<<endl;
}

int main() {
    ios_base::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    
    int t;
    cin >> t;  // Uncomment for multiple test cases
    while (t--) {
        solve();
    }
    
    return 0;
}